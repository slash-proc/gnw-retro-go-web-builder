/**
 * Ukrainian numeral agreement: nominative singular after 1 (but not 11), nominative plural
 * after 2-4 (but not 12-14), genitive plural otherwise. Every count in this file that sits
 * directly in front of a noun goes through it, because `1 тек` and `5 тека` are both wrong.
 */
function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && !(mod100 >= 12 && mod100 <= 14)) return few;
  return many;
}

